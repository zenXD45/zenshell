#!/usr/bin/env python3
"""Apply a HyprZen theme to GTK, Qt and KDE.

theme-switch.sh calls this after Hyprland and Kitty have been switched. The
palette comes from themes/palettes.json (generated by gen-themes.py from the
same TOML source as Hyprland), so the island, GTK apps and Qt apps cannot
disagree about what a theme looks like.

What it updates:
  * ~/.config/gtk-{3,4}.0/settings.ini   theme name + dark preference
  * ~/.config/xsettingsd/xsettingsd.conf  Net/ThemeName for non-gsettings apps
  * ~/.local/share/color-schemes/         one KDE colour scheme per theme
  * ~/.config/qt6ct/qt6ct.conf            palette + Fusion style
  * ~/.config/qt5ct/qt5ct.conf            palette + Fusion style
  * ~/.config/kdeglobals                  KDE / Dolphin / Qt app colours
  * gsettings                             GNOME/GTK consumers inside Hyprland

Colours themselves reach GTK through themes/<slug>.css, which the user
gtk-3.0/gtk.css and gtk-4.0/gtk.css import (see gen-themes.py).

Usage:
    apply-appearance.py <theme-slug>
"""

from __future__ import annotations

import configparser
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
HYPR_THEMES = HOME / ".config" / "hypr" / "themes"
PALETTES = HYPR_THEMES / "palettes.json"
SYSTEM_THEMES = Path("/usr/share/themes")

# KDE colour scheme groups that every Qt/KDE app reads.
COLOR_GROUPS = (
    "Colors:Window",
    "Colors:View",
    "Colors:Button",
    "Colors:Selection",
    "Colors:Tooltip",
    "Colors:Complementary",
    "Colors:Header",
    "Colors:Header][Inactive",
)


def die(message: str) -> None:
    print(f"apply-appearance: {message}", file=sys.stderr)
    raise SystemExit(1)


def strip_hash(value: str) -> str:
    return value.lstrip("#")


def rgb(value: str) -> tuple[int, int, int]:
    h = strip_hash(value)
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def kde_rgb(value: str) -> str:
    r, g, b = rgb(value)
    return f"{r},{g},{b}"


def mix(a: str, b: str, amount: float) -> str:
    ar, ag, ab = rgb(a)
    br, bg, bb = rgb(b)
    return "#{:02x}{:02x}{:02x}".format(
        round(ar + (br - ar) * amount),
        round(ag + (bg - ag) * amount),
        round(ab + (bb - ab) * amount),
    )


def luminance(value: str) -> float:
    def channel(v: int) -> float:
        s = v / 255
        return s / 12.92 if s <= 0.03928 else ((s + 0.055) / 1.055) ** 2.4

    r, g, b = rgb(value)
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def readable_on(background: str, dark: str = "#000000") -> str:
    return dark if luminance(background) > 0.45 else "#ffffff"


def theme_exists(name: str) -> bool:
    return (HOME / ".themes" / name).is_dir() or (SYSTEM_THEMES / name).is_dir()


def resolve_gtk_theme(entry: dict) -> str:
    """Use the declared port, falling back to adw-gtk3 if it is not installed."""
    declared = entry.get("gtk_theme") or ""
    dark = entry.get("dark", True)
    fallback = "adw-gtk3-dark" if dark else "adw-gtk3"
    for candidate in (declared, fallback):
        if candidate and theme_exists(candidate):
            return candidate
    return fallback


def ini_writer(path: Path) -> configparser.RawConfigParser:
    parser = configparser.RawConfigParser(strict=False, interpolation=None)
    parser.optionxform = str  # keep gtk-theme-name, not gtk-theme-name lowercased
    if path.exists():
        parser.read(path, encoding="utf-8")
    return parser


def save_ini(parser: configparser.RawConfigParser, path: Path, header: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8") as handle:
        if header:
            handle.write(header)
        parser.write(handle)
    tmp.replace(path)


def update_gtk_settings(path: Path, gtk_theme: str, dark: bool) -> None:
    parser = ini_writer(path)
    if not parser.has_section("Settings"):
        parser.add_section("Settings")
    parser.set("Settings", "gtk-theme-name", gtk_theme)
    parser.set("Settings", "gtk-application-prefer-dark-theme", "1" if dark else "0")
    save_ini(parser, path)


def update_xsettingsd(gtk_theme: str) -> None:
    path = HOME / ".config" / "xsettingsd" / "xsettingsd.conf"
    if not path.exists():
        return
    lines = []
    replaced = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("Net/ThemeName"):
            lines.append(f'Net/ThemeName "{gtk_theme}"')
            replaced = True
        else:
            lines.append(line)
    if not replaced:
        lines.insert(0, f'Net/ThemeName "{gtk_theme}"')
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def color_scheme_sections(entry: dict) -> dict[str, dict[str, str]]:
    colors = entry["colors"]
    palette = entry.get("palette", {})
    bg = "#" + strip_hash(colors["bg"])
    surface = "#" + strip_hash(colors["surface"])
    overlay = "#" + strip_hash(colors["overlay"])
    accent = "#" + strip_hash(colors["accent"])
    fg = "#" + strip_hash(colors["fg"])
    subfg = "#" + strip_hash(colors["subfg"])
    urgent = "#" + strip_hash(colors["urgent"])
    green = "#" + strip_hash(palette.get("green", colors["urgent"]))
    yellow = "#" + strip_hash(palette.get("yellow", colors["accent"]))
    blue = "#" + strip_hash(palette.get("blue", colors["accent"]))
    magenta = "#" + strip_hash(palette.get("magenta", colors["accent"]))
    on_accent = readable_on(accent, dark=bg)
    button = mix(bg, surface, 0.5)

    def group(background: str, alternate: str, foreground: str = fg) -> dict[str, str]:
        return {
            "BackgroundAlternate": kde_rgb(alternate),
            "BackgroundNormal": kde_rgb(background),
            "DecorationFocus": kde_rgb(accent),
            "DecorationHover": kde_rgb(accent),
            "ForegroundActive": kde_rgb(accent),
            "ForegroundInactive": kde_rgb(subfg),
            "ForegroundLink": kde_rgb(blue),
            "ForegroundNegative": kde_rgb(urgent),
            "ForegroundNeutral": kde_rgb(yellow),
            "ForegroundNormal": kde_rgb(foreground),
            "ForegroundPositive": kde_rgb(green),
            "ForegroundVisited": kde_rgb(magenta),
        }

    selection = group(accent, accent, on_accent)
    selection["ForegroundActive"] = kde_rgb(on_accent)
    selection["ForegroundInactive"] = kde_rgb(on_accent)
    selection["ForegroundLink"] = kde_rgb(on_accent)
    selection["ForegroundNegative"] = kde_rgb(on_accent)
    selection["ForegroundNeutral"] = kde_rgb(on_accent)
    selection["ForegroundPositive"] = kde_rgb(on_accent)
    selection["ForegroundVisited"] = kde_rgb(on_accent)

    return {
        "Colors:Window": group(bg, surface),
        "Colors:View": group(surface, bg),
        "Colors:Button": group(surface, button),
        "Colors:Selection": selection,
        "Colors:Tooltip": group(overlay, surface),
        "Colors:Complementary": group(overlay, bg),
        "Colors:Header": group(surface, bg),
        "Colors:Header][Inactive": group(bg, surface, subfg),
    }


def write_color_scheme(entry: dict, slug: str) -> Path:
    scheme_dir = HOME / ".local" / "share" / "color-schemes"
    scheme_dir.mkdir(parents=True, exist_ok=True)
    name = f"HyprZen-{entry['name']}"
    path = scheme_dir / f"{name}.colors"

    parser = configparser.RawConfigParser(strict=False, interpolation=None)
    parser.optionxform = str
    parser.add_section("ColorEffects:Disabled")
    for key, value in {
        "Color": "56,56,56",
        "ColorAmount": "0",
        "ColorEffect": "0",
        "ContrastAmount": "0.65",
        "ContrastEffect": "1",
        "IntensityAmount": "0.1",
        "IntensityEffect": "2",
    }.items():
        parser.set("ColorEffects:Disabled", key, value)
    parser.add_section("ColorEffects:Inactive")
    for key, value in {
        "ChangeSelectionColor": "true",
        "Color": "112,111,110",
        "ColorAmount": "0.025",
        "ColorEffect": "2",
        "ContrastAmount": "0.1",
        "ContrastEffect": "2",
        "Enable": "false",
        "IntensityAmount": "0",
        "IntensityEffect": "0",
    }.items():
        parser.set("ColorEffects:Inactive", key, value)

    for section, values in color_scheme_sections(entry).items():
        parser.add_section(section)
        for key, value in values.items():
            parser.set(section, key, value)

    parser.add_section("General")
    parser.set("General", "ColorScheme", name)
    parser.set("General", "Name", name)
    parser.set("General", "shadeSortColumn", "true")

    save_ini(parser, path)
    return path


def update_qtct(path: Path, scheme: Path) -> None:
    parser = ini_writer(path)
    if not parser.has_section("Appearance"):
        parser.add_section("Appearance")
    parser.set("Appearance", "color_scheme_path", str(scheme))
    parser.set("Appearance", "custom_palette", "true")
    # Fusion honours the generated palette directly. The previous kvantum-dark
    # style painted its own baked-in SVG colours, so palette changes were lost.
    parser.set("Appearance", "style", "Fusion")
    parser.set("Appearance", "standard_dialogs", "gtk3")
    save_ini(parser, path)


def update_kdeglobals(entry: dict) -> None:
    path = HOME / ".config" / "kdeglobals"
    parser = ini_writer(path)
    for section, values in color_scheme_sections(entry).items():
        if not parser.has_section(section):
            parser.add_section(section)
        for key, value in values.items():
            parser.set(section, key, value)

    colors = entry["colors"]
    bg = "#" + strip_hash(colors["bg"])
    surface = "#" + strip_hash(colors["surface"])
    accent = "#" + strip_hash(colors["accent"])
    fg = "#" + strip_hash(colors["fg"])
    subfg = "#" + strip_hash(colors["subfg"])
    if not parser.has_section("WM"):
        parser.add_section("WM")
    for key, value in {
        "activeBackground": kde_rgb(surface),
        "activeBlend": kde_rgb(accent),
        "activeForeground": kde_rgb(fg),
        "inactiveBackground": kde_rgb(bg),
        "inactiveBlend": kde_rgb(subfg),
        "inactiveForeground": kde_rgb(subfg),
    }.items():
        parser.set("WM", key, value)
    save_ini(parser, path)


def apply_gsettings(gtk_theme: str, dark: bool) -> None:
    if not os.environ.get("DBUS_SESSION_BUS_ADDRESS"):
        return
    gsettings = shutil.which("gsettings")
    if not gsettings:
        return
    commands = (
        (["gtk-theme", gtk_theme]),
        (["color-scheme", "prefer-dark" if dark else "prefer-light"]),
    )
    for key, value in commands:
        subprocess.run(
            [gsettings, "set", "org.gnome.desktop.interface", key, value],
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )


def notify_running_apps() -> None:
    # XSettings consumers (GTK3 apps that are not gsettings-based).
    pkill = shutil.which("pkill")
    if pkill:
        subprocess.run([pkill, "-HUP", "-x", "xsettingsd"], check=False,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    # KDE / Qt apps watch kdeglobals, but a nudge helps Plasma-integrated ones.
    if os.environ.get("DBUS_SESSION_BUS_ADDRESS") and shutil.which("dbus-send"):
        subprocess.run(
            [
                "dbus-send", "--session", "--type=signal", "/KGlobalSettings",
                "org.kde.KGlobalSettings.notifyChange", "int32:0", "int32:0",
            ],
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    # Touch the CSS entry points so GTK4 apps that monitor their user stylesheet
    # notice the regenerated colours on the next redraw.
    for css in (HOME / ".config" / "gtk-3.0" / "gtk.css",
                HOME / ".config" / "gtk-4.0" / "gtk.css"):
        try:
            os.utime(css)
        except OSError:
            pass


def main() -> int:
    if len(sys.argv) != 2:
        die("usage: apply-appearance.py <theme-slug>")
    slug = sys.argv[1]

    try:
        manifest = json.loads(PALETTES.read_text(encoding="utf-8"))
    except FileNotFoundError:
        die(f"{PALETTES} missing — run hyprzen/scripts/gen-themes.py")
    except json.JSONDecodeError as exc:
        die(f"{PALETTES} is not valid JSON: {exc}")

    entry = manifest.get(slug)
    if not entry:
        die(f"unknown theme '{slug}' in {PALETTES}")

    gtk_theme = resolve_gtk_theme(entry)
    dark = bool(entry.get("dark", True))
    scheme = write_color_scheme(entry, slug)

    update_gtk_settings(HOME / ".config" / "gtk-3.0" / "settings.ini", gtk_theme, dark)
    update_gtk_settings(HOME / ".config" / "gtk-4.0" / "settings.ini", gtk_theme, dark)
    update_xsettingsd(gtk_theme)
    update_qtct(HOME / ".config" / "qt6ct" / "qt6ct.conf", scheme)
    update_qtct(HOME / ".config" / "qt5ct" / "qt5ct.conf", scheme)
    update_kdeglobals(entry)
    apply_gsettings(gtk_theme, dark)
    notify_running_apps()

    print(f"apply-appearance: {entry['name']} → GTK {gtk_theme}, Qt Fusion, KDE colours")
    return 0


if __name__ == "__main__":
    sys.exit(main())
