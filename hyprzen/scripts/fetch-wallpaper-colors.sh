#!/usr/bin/env bash
# =============================================================
#  Fetch wallpaper-derived colors via matugen and output as
#  Hyprlang variables + CSS @define-color for overlay usage.
#  Called by theme-switch.sh to add wallpaper accent to any theme.
# =============================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
CURRENT_WALLPAPER="$HOME/wallpapers/current"
HYPR_THEMES_DIR="$HOME/.config/hypr/themes"
MATUGEN_CONFIG="$HOME/.config/matugen/config.toml"
MATUGEN_TOML="$HYPR_THEMES_DIR/source/matugen.toml"

# Output files (overlays applied on top of selected theme)
WALLPAPER_CONF="$HYPR_THEMES_DIR/wallpaper.conf"
WALLPAPER_CSS="$HYPR_THEMES_DIR/wallpaper.css"
WALLPAPER_LUA="$HYPR_THEMES_DIR/wallpaper.lua"

# Check prerequisites
if ! command -v matugen >/dev/null 2>&1; then
    echo "fetch-wallpaper-colors: matugen not found" >&2
    exit 1
fi

if [ ! -f "$CURRENT_WALLPAPER" ]; then
    echo "fetch-wallpaper-colors: wallpaper not found at $CURRENT_WALLPAPER" >&2
    exit 1
fi

if [ ! -f "$MATUGEN_CONFIG" ]; then
    echo "fetch-wallpaper-colors: matugen config not found" >&2
    exit 1
fi

# Run matugen to generate wallpaper palette into the matugen.toml source file
# This is the same command used for the "matugen" theme, but we don't run gen-themes.py
# since we only need the overlay files, not full theme regeneration.
if ! matugen -c "$MATUGEN_CONFIG" image "$CURRENT_WALLPAPER" \
        --prefer saturation --source-color-index 0 >/dev/null 2>&1; then
    echo "fetch-wallpaper-colors: matugen failed" >&2
    exit 1
fi

# Parse the generated matugen.toml for colors
if [ ! -f "$MATUGEN_TOML" ]; then
    echo "fetch-wallpaper-colors: matugen.toml not generated" >&2
    exit 1
fi

# Extract colors using grep/sed (TOML is simple enough for this)
# Colors are in [colors] section with format: key = "#rrggbb"
get_toml_color() {
    local key="$1"
    local file="$2"
    # Match: key = "#rrggbb" (with optional spaces)
    grep -E "^${key}[[:space:]]*=[[:space:]]*\"#[0-9a-fA-F]{6}\"" "$file" | \
        head -1 | sed -E 's/.*"#([0-9a-fA-F]{6})".*/\1/'
}

PRIMARY=$(get_toml_color "accent" "$MATUGEN_TOML")
SECONDARY=$(get_toml_color "urgent" "$MATUGEN_TOML")  # urgent used as secondary
TERTIARY=$(get_toml_color "subfg" "$MATUGEN_TOML")   # fallback
BACKGROUND=$(get_toml_color "bg" "$MATUGEN_TOML")
SURFACE=$(get_toml_color "surface" "$MATUGEN_TOML")
ON_PRIMARY="#ffffff"  # default, matugen TOML doesn't have on_primary
ON_BACKGROUND=$(get_toml_color "fg" "$MATUGEN_TOML")

# Fallback: if accent not found, try primary from template mapping
if [ -z "$PRIMARY" ]; then
    PRIMARY=$(get_toml_color "primary" "$MATUGEN_TOML" 2>/dev/null || echo "")
fi

# Validate we got at least the primary accent
if [ -z "$PRIMARY" ]; then
    echo "fetch-wallpaper-colors: failed to extract accent color from matugen.toml" >&2
    exit 1
fi

# RGBA helper for CSS
rgba() {
    local hex="${1#\#}"
    local alpha="$2"
    local r=$((16#${hex:0:2}))
    local g=$((16#${hex:2:2}))
    local b=$((16#${hex:4:2}))
    echo "rgba($r, $g, $b, $alpha)"
}

# Generate Hyprlang overlay conf (sourced AFTER theme conf)
cat > "$WALLPAPER_CONF" <<EOF
# Wallpaper-derived colors (matugen) — sourced after theme to override accents
# Generated by fetch-wallpaper-colors.sh
\$wallpaper_accent = $PRIMARY
\$wallpaper_accent_soft = ${PRIMARY}CC
\$wallpaper_accent_glow = ${PRIMARY}59
\$wallpaper_secondary = ${SECONDARY:-$PRIMARY}
\$wallpaper_tertiary = ${TERTIARY:-$PRIMARY}
\$wallpaper_bg = ${BACKGROUND:-$PRIMARY}
\$wallpaper_surface = ${SURFACE:-$PRIMARY}
\$wallpaper_on_accent = ${ON_PRIMARY:-ffffff}
\$wallpaper_on_bg = ${ON_BACKGROUND:-$PRIMARY}

# Override theme accent with wallpaper accent (comment out to keep theme accent)
\$accent = $PRIMARY
\$border_active = rgba(${PRIMARY}ff)
EOF

# Generate CSS overlay (imported after theme CSS)
cat > "$WALLPAPER_CSS" <<EOF
/* Wallpaper-derived colors (matugen) — imported after theme to override accents */
@define-color wallpaper_accent       #${PRIMARY};
@define-color wallpaper_accent_soft  $(rgba "#${PRIMARY}" 0.18);
@define-color wallpaper_accent_glow  $(rgba "#${PRIMARY}" 0.35);
@define-color wallpaper_secondary    #${SECONDARY:-$PRIMARY};
@define-color wallpaper_tertiary     #${TERTIARY:-$PRIMARY};
@define-color wallpaper_bg           #${BACKGROUND:-$PRIMARY};
@define-color wallpaper_surface      #${SURFACE:-$PRIMARY};
@define-color wallpaper_on_accent    #${ON_PRIMARY#\#};
@define-color wallpaper_on_bg        #${ON_BACKGROUND:-$PRIMARY};

/* Override theme accent with wallpaper accent */
@define-color accent                 #${PRIMARY};
@define-color accent_soft            $(rgba "#${PRIMARY}" 0.18);
@define-color accent_glow            $(rgba "#${PRIMARY}" 0.35);
@define-color border_color           $(rgba "#${PRIMARY}" 0.20);
EOF

# Generate Lua overlay (required AFTER the theme; assigns globals to override)
# Theme .lua files assign globals (accent = "..."), not a returned table, so this
# file must do the same. Only accent-related globals are overridden so the theme's
# base palette (bg/surface/text) is preserved.
cat > "$WALLPAPER_LUA" <<EOF
-- Wallpaper-derived accent overrides (matugen) — required after the theme.
-- Assigns globals (same style as themes/*.lua) so they override the theme.
-- Generated by fetch-wallpaper-colors.sh
accent = "${PRIMARY}"
border_active = "rgba(${PRIMARY}ff)"
EOF

echo "fetch-wallpaper-colors: wrote wallpaper overlay (accent #${PRIMARY})"